// Hazel vs the baselines, measured against the answer key (ticket 13). eval/ is the only code that reads answer keys.
//
//   bun run eval --run r13-20261025T072822                      seed 13: Hazel's recorded run + both baselines, live CRS
//   bun run eval --run <run_id> --spec <seed 99 spec>           the held-out seed
//   bun run eval --run <run_id> --crs recorded                  baselines on the recorded CRS answers (labelled)
//   bun run eval --run <run_id> --write                         also write docs/PROOF.md (only on frozen detection code)
//
// Hazel's numbers come only from her run's event rows (runs/<run_id>/events.jsonl, else Supabase); the baselines run
// here, now, on the same portfolio. Nothing is typed in by hand.
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { parseArgs } from "node:util";
import { FREEZE_TAG, freezeStatus } from "@/data/freeze";
import { generate, type AnswerKey } from "@/data/generate";
import { EventSchema, type Event } from "@/lib/contracts/event";
import type { LoanStatus } from "@/lib/contracts/loan";
import { defaultCrsClient } from "@/lib/crs";
import { checkEverything, fixedRules, RULE_KINDS, type AgentResult } from "./baselines";

/** Hazel's result, read only from her run's rows: the last status per loan, the last budget, the charged CRS calls. */
export function hazelFromEvents(events: readonly Event[]): AgentResult {
  const rows = [...events].sort((a, b) => a.seq - b.seq);
  const statuses = new Map<string, LoanStatus>();
  for (const e of rows)
    if (e.type === "status_changed" && typeof e.result.status === "string")
      for (const id of e.loan_ids) statuses.set(id, e.result.status as LoanStatus);
  const crs = rows.filter((e) => e.type === "budget_spent" && e.tool?.startsWith("crs_"));
  const first = rows[0], last = rows.at(-1);
  return {
    agent: "Threadpull (Hazel)", statuses,
    acorns: last ? last.budget.spent : 0,
    crs_calls: crs.length, simulated_calls: crs.filter((e) => e.simulated).length,
    questions: rows.filter((e) => e.type === "question_asked").length,
    runtime_ms: first && last ? Date.parse(last.ts) - Date.parse(first.ts) : 0,
  };
}

export type Score = {
  agent: string;
  ring_found: number; ring_total: number; // ring members marked Investigate
  innocents_flagged: number; innocents_total: number; // lookalikes and risky-but-real loans marked Investigate
  other_flagged: number; // any other loan marked Investigate (not ring, not a review case)
  review_right: number; review_total: number; // review cases with their expected status
  acorns: number; crs_calls: number; simulated_calls: number; questions: number; runtime_ms: number;
};

export function score(r: AgentResult, key: AnswerKey): Score {
  const flagged = (id: string) => r.statuses.get(id) === "Investigate";
  const ring = key.rings.flatMap((x) => x.loan_ids);
  const innocent = [...key.lookalikes.flatMap((x) => x.loan_ids), ...key.risky_real.flatMap((x) => x.loan_ids)];
  const review = key.review_cases.flatMap((x) => x.loan_ids.map((id) => [id, x.expected_status] as const));
  const known = new Set([...ring, ...innocent, ...review.map(([id]) => id)]);
  return {
    agent: r.agent,
    ring_found: ring.filter(flagged).length, ring_total: ring.length,
    innocents_flagged: innocent.filter(flagged).length, innocents_total: innocent.length,
    other_flagged: [...r.statuses.keys()].filter((id) => !known.has(id) && flagged(id)).length,
    review_right: review.filter(([id, want]) => r.statuses.get(id) === want).length, review_total: review.length,
    acorns: r.acorns, crs_calls: r.crs_calls, simulated_calls: r.simulated_calls, questions: r.questions, runtime_ms: r.runtime_ms,
  };
}

const n = (x: number) => x.toLocaleString("en-US");
const ruleKinds = () => {
  const words = RULE_KINDS.map((k) => (k === "ip_address" ? "IP address" : k === "address" ? "street address" : k.replace("_", " ")));
  return `${words.slice(0, -1).join(", ")} or ${words.at(-1)}`;
};
const secs = (ms: number) => (ms < 1000 ? "<1 s" : `${Math.round(ms / 100) / 10} s`);

export type ProofContext = { seed: number; run_id: string; crs: string; commit: string; detector: string; generated_at: string };

export function renderProof(scores: Score[], ctx: ProofContext): string {
  const row = (s: Score) => `| ${s.agent} | ${s.ring_found} of ${s.ring_total} | ${s.innocents_flagged} of ${s.innocents_total} | ${n(s.other_flagged)} | ${s.review_right} of ${s.review_total} | ${n(s.acorns)} | ${s.crs_calls}${s.simulated_calls ? ` (${s.simulated_calls} simulated)` : ""} | ${s.questions} | ${secs(s.runtime_ms)} |`;
  return `## Seed ${ctx.seed}

Generated by \`bun run eval\` on ${ctx.generated_at} from commit \`${ctx.commit}\` (detector: ${ctx.detector}). Hazel's numbers come from
the event rows of run \`${ctx.run_id}\`; the baselines ran on the same portfolio with CRS ${ctx.crs === "live" ? "live (sandbox)" : "answers replayed from data/crs-recordings (recorded, not live)"}.

| Agent | Ring found | Innocents flagged | Other loans flagged | Review cases right | Acorns | CRS calls | Questions | Runtime |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
${scores.map(row).join("\n")}

- **Ring found:** ring members marked Investigate. **Innocents flagged:** lookalikes (a shared building, household, employer
  or dealer burst with an innocent explanation) and risky-but-real loans marked Investigate. **Other loans flagged:** any
  other loan marked Investigate. **Review cases right:** fraud alert, frozen bureau and bureau disagreement cases with
  their expected status.
- **Check everything** runs all four CRS products on every loan with no budget; statuses come from the CRS answers alone.
- **Fixed rules** flags every loan sharing a ${ruleKinds()} with another loan, then spends the
  same budget as Hazel (60 acorns) on identity checks, flagged loans first.
- Acorn prices are design choices (\`lib/contracts/tool-result.ts\`); each shows its real unit there. A loan an agent never
  gave a status counts as not flagged.
`;
}

if (import.meta.main) {
  const { values: args } = parseArgs({ options: {
    run: { type: "string" },
    spec: { type: "string", default: "data/patterns/seed13.json" },
    crs: { type: "string", default: "live" }, // live | recorded
    write: { type: "boolean", default: false },
  } });
  if (!args.run) { console.error("usage: bun run eval --run <run_id> [--spec <spec>] [--crs live|recorded] [--write]"); process.exit(2); }

  const gen = generate(args.spec!, mkdtempSync(join(tmpdir(), "tp-")), mkdtempSync(join(tmpdir(), "tp-")));
  const key: AnswerKey = JSON.parse(readFileSync(join(gen.keyDir, "answer_key.json"), "utf8"));

  // Hazel's rows: the local log if this machine ran it, else the shared events table (read-only, anon key)
  const local = join("runs", args.run, "events.jsonl");
  let raw: unknown[];
  if (existsSync(local)) raw = readFileSync(local, "utf8").trim().split("\n").map((l) => JSON.parse(l));
  else {
    const url = process.env.NEXT_PUBLIC_SUPABASE_URL ?? process.env.SUPABASE_URL, anon = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
    if (!url || !anon) { console.error(`no ${local}, and Supabase isn't configured to read run ${args.run}`); process.exit(1); }
    const res = await fetch(`${url}/rest/v1/events?run_id=eq.${encodeURIComponent(args.run)}&order=seq`, { headers: { apikey: anon, Authorization: `Bearer ${anon}` } });
    raw = res.ok ? await res.json() : [];
  }
  const events = raw.map((r) => EventSchema.parse(r));
  if (!events.length) { console.error(`run ${args.run} has no event rows`); process.exit(1); }
  const runSeed = events.find((e) => e.type === "run_started")?.result.seed;
  if (runSeed !== undefined && runSeed !== gen.seed) { console.error(`run ${args.run} is on seed ${runSeed}, the spec is seed ${gen.seed}`); process.exit(1); }

  const crs = args.crs === "recorded" ? (await import("@/tests/crs-replay")).client() : defaultCrsClient();
  const results = [hazelFromEvents(events), await fixedRules(gen.normalized, crs), await checkEverything(gen.normalized, crs)];
  const scores = results.map((r) => score(r, key));

  const freeze = freezeStatus();
  const frozen = freeze.frozen && freeze.changed.length === 0;
  const commit = spawnSync("git", ["rev-parse", "--short", "HEAD"], { encoding: "utf8" }).stdout.trim();
  const md = renderProof(scores, { seed: gen.seed, run_id: args.run, crs: args.crs!, commit,
    detector: frozen && freeze.frozen ? `${FREEZE_TAG} ${freeze.commit}` : "not frozen", generated_at: new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC" });
  console.log(md);
  const out = join("runs", args.run, `proof-seed${gen.seed}.md`);
  if (existsSync(join("runs", args.run))) { writeFileSync(out, md); console.log(`saved: ${out}`); }
  if (args.write) {
    if (!frozen) { console.error(`\nNot written to docs/PROOF.md: detection code isn't frozen (${freeze.frozen ? `changed since ${FREEZE_TAG}` : freeze.reason}). See bun run freeze:check.`); process.exit(1); }
    const proof = readFileSync("docs/PROOF.md", "utf8");
    const marker = `## Seed ${gen.seed}\n`;
    const start = proof.indexOf(marker);
    const next = start < 0 ? -1 : proof.indexOf("\n## Seed ", start + marker.length);
    const updated = start < 0 ? `${proof.trimEnd()}\n\n${md}` : `${proof.slice(0, start)}${md}${next < 0 ? "" : proof.slice(next + 1)}`;
    writeFileSync("docs/PROOF.md", updated);
    console.log("docs/PROOF.md updated.");
  }
}
